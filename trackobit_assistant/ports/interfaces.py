from typing import Any, Protocol
from trackobit_assistant.schemas.models import CommandSpec, TicketResult, VehicleSnapshot

class SessionStore(Protocol):
    def create_session(self) -> dict[str, Any]: ...
    def list_sessions(self, user_id: str | None = None) -> list[dict[str, Any]]: ...
    def get_session(self, session_id: str) -> dict[str, Any] | None: ...
    def state_for(self, session_id: str) -> dict[str, Any] | None: ...
    def save_graph_result(self, session_id: str, state: dict[str, Any]) -> None: ...
    def append_message(self, session_id: str, message: dict[str, Any]) -> None: ...
    def get_summary(self, session_id: str) -> str: ...

class VehicleApiClient(Protocol):
    def get_vehicle(self, vehicle_no: str) -> VehicleSnapshot: ...

class TicketClient(Protocol):
    def create(self, summary: str, reason: str, metadata: dict[str, Any]) -> TicketResult: ...

class CommandRegistry(Protocol):
    def get_commands(self, device_type: str) -> list[CommandSpec]: ...
    def get_command(self, device_type: str, command_id: str) -> CommandSpec | None: ...

class KnowledgeBase(Protocol):
    def search(self, query: str, k: int = 4) -> list[dict[str, Any]]: ...
